// =============================================================================
//  Job DSL seed script — the single source of truth for this repo's Jenkins jobs.
//
//  Run by the "seed" job (see Jenkinsfile.seed), which invokes the Job DSL plugin
//  against this file. The seed reconciles Jenkins to match this script:
//
//    * add an entry to `pipelines` below  -> the job is CREATED on the next seed run
//    * change an entry (script/triggers)  -> the job is UPDATED to match
//    * remove an entry                    -> the job is DELETED
//
//  So jobs are never hand-created in the UI: edit this file, commit, let the seed run.
//
//  Repo URL, branch and git credentials are injected by Jenkinsfile.seed as
//  environment variables (SEED_REPO_URL / SEED_BRANCH / SEED_CREDENTIALS_ID).
// =============================================================================

String repoUrl = SEED_REPO_URL
String branch  = SEED_BRANCH               // already in "*/develop" refspec form
String credId  = SEED_CREDENTIALS_ID       // may be empty when the agent key already has access
String folderName = 'bankstmt-audit'

folder(folderName) {
    description('CI/CD for bankstmt-audit (SQS -> MySQL audit ingestion microservice, deployed to Elastic Beanstalk).\n\nGenerated by jenkins/jobs.groovy (Job DSL) — do not edit these jobs by hand; changes are overwritten by the seed job.')
}

// =============================================================================
//  BRANCH POLICY — the single source of truth for which branches get a pipeline.
//
//  The multibranch `branches` job builds `Jenkinsfile` for each allowed branch
//  (build + unit test always; deploy to Elastic Beanstalk only on develop/main).
//  To authorise a new branch, add it to `allowedBranches` (space-separated,
//  shell-style wildcards allowed) — the ONLY place a branch is granted a pipeline.
// =============================================================================
String allowedBranches = 'develop main'

multibranchPipelineJob("${folderName}/branches") {
    displayName("branches (${allowedBranches})")
    description("Per-branch CI/CD (runs Jenkinsfile: build + unit test, deploy to EB on develop/main). Branch discovery is filtered to: ${allowedBranches}.\n\nGenerated by Job DSL (jenkins/jobs.groovy) — do not edit by hand.")
    branchSources {
        branchSource {
            source {
                git {
                    id("${folderName}-branches")
                    remote(repoUrl)
                    if (credId) {
                        credentialsId(credId)
                    }
                    traits {
                        gitBranchDiscovery()
                        headWildcardFilter {
                            includes(allowedBranches)
                            excludes('')
                        }
                    }
                }
            }
        }
    }
    factory {
        workflowBranchProjectFactory {
            scriptPath('Jenkinsfile')
        }
    }
    orphanedItemStrategy {
        discardOldItems {
            numToKeepStr('10')
        }
    }
    triggers {
        periodicFolderTrigger {
            interval('1d')
        }
    }
}

// One entry per pipeline. `poll` = SCM-poll cron (null to disable); `cron` = timer cron (null to
// disable). `branch` pins the job to a specific branch (null = track the seed branch).
//
// `unit`   polls often for fast feedback.
// `deploy` is the build+test+EB-deploy pipeline (also the target the release gates trigger).
// The release GATES enforce the criterion: the branch's tests must pass before it releases.
List<Map> pipelines = [
    [name: 'unit',   script: 'Jenkinsfile.unit', poll: 'H/5 * * * *', cron: null, branch: null,
     desc: 'Unit tests (./gradlew test). Mocks only, no Docker.'],
    [name: 'deploy', script: 'Jenkinsfile',      poll: null,         cron: null, branch: null,
     desc: 'Build the jar and deploy to Elastic Beanstalk (bankstmt-audit-prod), with a health gate. Trigger by the release gates or manually.'],
    [name: 'release-develop', script: 'Jenkinsfile.release-develop', poll: null, cron: null, branch: '*/develop',
     desc: 'RELEASE GATE for develop — runs the tests against develop and releases (deploy) only if they pass.'],
    [name: 'release-main',    script: 'Jenkinsfile.release-main',    poll: null, cron: null, branch: '*/main',
     desc: 'RELEASE GATE for main — runs the tests against main and releases (deploy) only if they pass.'],
]

pipelines.each { Map p ->
    String jobBranch = (p.branch ?: branch) as String
    pipelineJob("${folderName}/${p.name}") {
        description("${p.desc}\n\nGenerated by Job DSL (jenkins/jobs.groovy) — do not edit by hand.")
        logRotator {
            numToKeep(20)
        }
        if (p.poll || p.cron) {
            triggers {
                if (p.poll) {
                    scm(p.poll as String)
                }
                if (p.cron) {
                    cron(p.cron as String)
                }
            }
        }
        definition {
            cpsScm {
                scm {
                    git {
                        remote {
                            url(repoUrl)
                            if (credId) {
                                credentials(credId)
                            }
                        }
                        branch(jobBranch)
                    }
                }
                scriptPath(p.script as String)
                lightweight(true)
            }
        }
    }
}
